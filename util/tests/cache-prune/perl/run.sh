# `system df` fails once a builder prune ran: a cross-source before/after pair).
DFIX="$SANDBOX/docker-fix"
DSTUBS="$SANDBOX/docker-stubs"
mkdir -p "$DFIX" "$DSTUBS" "$SANDBOX/dr-root/homelab"

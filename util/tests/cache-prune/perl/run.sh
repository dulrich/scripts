# Hermetic regression tests for util/cache-prune/perl/cache-prune.pl, the cache-prune tool (the
# util/cache-prune.sh shim execs it). Core logic runs in-process via unit.pl and docker.pl (faked
# seams); the CLI, the fleet-module seam and the golden-output cases (golden/: one full dump
# per family -- stdout, stderr, exit status and tool-call log -- with variants asserted as
# deltas against it) run as real subprocesses
# with stub uv/npm/pip/bun/cargo/docker/gio executables on PATH, inside a mktemp sandbox.
for _a in "$@"; do case "$_a" in --help|-h)
	printf 'usage: %s %s\n' "${0##*/}" ''
	printf '%s\n' 'Hermetic regression tests for util/cache-prune/perl/cache-prune.pl; takes no arguments.'
	exit 0;; esac; done
# >>> shguard modes=exec (generated by shell-disposition-gate --guard; do not edit)
case $(realpath -- "$0" 2>/dev/null) in */'util/tests/cache-prune/perl/run.sh') _shguard_m='exec' ;; *) if [ "${SHGUARD_MODE-}" = 'pipe' ]; then _shguard_m='pipe'; else _shguard_m='source'; fi ;; esac
# shellcheck disable=SC2317
case $_shguard_m in
  exec) unset _shguard_m ;;
  *) printf '%s: refusing %s invocation (supports: exec; pipe callers set SHGUARD_MODE=pipe)\n' 'run.sh' "$_shguard_m" >&2; unset _shguard_m; return 1 2>/dev/null || exit 1 ;;
esac
# <<< shguard
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
case " $* " in *" --build "*|*" --version "*)
	# shellcheck source=util/lib/build-id.sh
	. "$HERE/../../../lib/build-id.sh"; build_flags "$0" "$@";; esac
